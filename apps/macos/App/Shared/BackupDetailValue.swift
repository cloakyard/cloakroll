import SwiftUI

/// Keep each fact's label/value together without Form merging adjacent facts into one utterance.
struct BackupDetailValue: View {
    let title: String
    let value: String

    init(_ title: String, value: String) { self.title = title; self.value = value }

    var body: some View {
        LabeledContent(title, value: value)
            .accessibilityElement(children: .ignore)
            .accessibilityLabel(title)
            .accessibilityValue(value)
    }
}
